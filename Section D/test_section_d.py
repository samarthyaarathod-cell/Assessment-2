class OrderPlaceSerializer(serializers.ModelSerializer):
    class Meta:
        model = Order
        fields = ['id', 'customer_name', 'item', 'quantity', 'status', 'created_at']
        read_only_fields = ['id', 'status', 'created_at']

    def validate_customer_name(self, value):
        cleaned = value.strip()
        if not cleaned:
            raise serializers.ValidationError("Customer name cannot be blank or whitespace.")
        return cleaned

    def validate_item(self, value):
        cleaned = value.strip()
        if not cleaned:
            raise serializers.ValidationError("Item cannot be blank.")
        return cleaned

    def validate_quantity(self, value):
        # Handles integer casting or validation cleanly
        if not isinstance(value, int) or isinstance(value, bool):
            raise serializers.ValidationError("Quantity must be a valid integer.")
        if value <= 0:
            raise serializers.ValidationError("Quantity must be a positive integer greater than zero.")
        return value


class CorrectedPlaceOrderView(APIView):
    """
    Refactored and hardened implementation following DRF best practices.
    """
    def post(self, request):
        serializer = OrderPlaceSerializer(data=request.data)
        if serializer.is_valid():
            # Save safely with fallback user association
            order = serializer.save(user_id=1)
            return Response(serializer.data, status=status.HTTP_201_CREATED)
        return Response(serializer.errors, status=status.HTTP_400_BAD_REQUEST)


